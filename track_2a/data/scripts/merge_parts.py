#!/usr/bin/env python3
"""Merge generator outputs from _parts/ into the published dataset files and
write STATS.md.

  python3 scripts/build_questions.py      # German master question bank
  python3 scripts/build_rubric.py
  python3 scripts/build_source_answers.py # FHGR-derived answers/transcripts
  python3 scripts/merge_parts.py          # this script
  python3 scripts/validate.py
"""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "_parts"
ANSWER_PARTS = ["src", "de1", "de2", "de3", "sit", "dif", "occ1", "occ2", "fr", "it", "gsw"]


def load(p):
    p = Path(p)
    if not p.exists():
        print(f"  (missing {p.relative_to(ROOT)})")
        return []
    return [json.loads(l) for l in p.open(encoding="utf-8") if l.strip()]


def dump(recs, p):
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("w", encoding="utf-8") as f:
        for r in recs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"  {p.relative_to(ROOT)}: {len(recs)}")


def main():
    # questions + translations
    qs = load(ROOT / "questions" / "questions.jsonl")
    tr = {t["id"]: t for t in load(P / "questions_translations.jsonl")}
    for q in qs:
        t = tr.get(q["id"])
        q["text"] = {"de": q["text"]["de"], **({"fr": t["fr"], "it": t["it"]} if t else {})}
        q["gsw_variants"] = (t or {}).get("gsw_variants", [])
        q["translation_review"] = "unreviewed" if t else None
    dump(qs, ROOT / "questions" / "questions.jsonl")

    answers, anns = [], []
    for part in ANSWER_PARTS:
        answers += load(P / f"answers_{part}.jsonl")
        anns += load(P / f"annotations_{part}.jsonl")
    order = {a["id"]: i for i, a in enumerate(answers)}
    anns.sort(key=lambda x: order.get(x["answer_id"], 10 ** 9))
    dump(answers, ROOT / "answers" / "answers.jsonl")
    dump(anns, ROOT / "annotations" / "annotations.jsonl")

    dump(load(P / "candidates.jsonl"), ROOT / "profiles" / "candidates.jsonl")
    dump(load(P / "postings.jsonl"), ROOT / "profiles" / "postings.jsonl")
    dump(load(P / "scenarios.jsonl"), ROOT / "scenarios" / "scenarios.jsonl")
    trs = load(P / "transcripts_src.jsonl")
    for f in sorted(P.glob("transcripts_t*.jsonl")):
        trs += load(f)
    dump(trs, ROOT / "transcripts" / "transcripts.jsonl")
    dump(load(P / "feedback_examples.jsonl"), ROOT / "feedback_examples" / "feedback_examples.jsonl")
    write_stats(qs, answers, anns, trs)


def table(counter, head, order=None):
    keys = order or sorted(counter, key=lambda k: (-counter[k], str(k)))
    rows = [f"| {head} | n |", "|---|---:|"] + [f"| {k} | {counter[k]} |" for k in keys if counter[k]]
    return "\n".join(rows)


def write_stats(qs, answers, anns, trs):
    cands = load(ROOT / "profiles" / "candidates.jsonl")
    posts = load(ROOT / "profiles" / "postings.jsonl")
    scen = load(ROOT / "scenarios" / "scenarios.jsonl")
    fb = load(ROOT / "feedback_examples" / "feedback_examples.jsonl")
    lv = Counter(a["quality_level"] for a in answers)
    lines = [
        "# Dataset statistics", "",
        "_Generated by `scripts/merge_parts.py` — do not edit by hand._", "",
        "| File | Records |", "|---|---:|",
        f"| questions/questions.jsonl | {len(qs)} |",
        f"| answers/answers.jsonl | {len(answers)} |",
        f"| annotations/annotations.jsonl | {len(anns)} |",
        f"| profiles/candidates.jsonl | {len(cands)} |",
        f"| profiles/postings.jsonl | {len(posts)} |",
        f"| scenarios/scenarios.jsonl | {len(scen)} |",
        f"| transcripts/transcripts.jsonl | {len(trs)} ({sum(len(t['turns']) for t in trs)} turns) |",
        f"| feedback_examples/feedback_examples.jsonl | {len(fb)} |", "",
        "## Questions", "", table(Counter(q["category"] for q in qs), "category"), "",
        table(Counter(q["flow_stage"] for q in qs), "flow_stage"), "",
        f"Translations: fr {sum(1 for q in qs if q['text'].get('fr'))}, it {sum(1 for q in qs if q['text'].get('it'))}; "
        f"Swiss-German variants: {sum(len(q.get('gsw_variants') or []) for q in qs)} "
        f"({', '.join(f'{k} {v}' for k, v in sorted(Counter(g['dialect'] for q in qs for g in q.get('gsw_variants') or []).items()))})", "",
        "## Answers", "",
        table(Counter(a["lang"] + (f"-{a['dialect']}" if a.get("dialect") else "") for a in answers), "language"), "",
        table(lv, "quality level", [1, 2, 3, 4]), "",
        table(Counter(a["answer_class"] for a in answers), "answer class", ["strong", "weak", "incomplete", "problematic"]), "",
        table(Counter("source (FHGR)" if not a["synthetic"] else "synthetic" for a in answers), "origin"), "",
        table(Counter(f for x in anns for f in x["problem_flags"]), "problem flag"), "",
        table(Counter(x["coach_action"] for x in anns), "coach action"), "",
        f"Answers linked to an occupation: {sum(1 for a in answers if a.get('occupation'))} "
        f"({len({a['occupation']['occupation_id'] for a in answers if a.get('occupation')})} distinct occupations)", "",
        "## Transcripts", "",
        table(Counter(f"{t['lang']}{('-' + t['dialect']) if t.get('dialect') else ''} / {t['situation']} / {t['overall_quality']}" for t in trs), "lang / situation / quality"), "",
        "## Feedback examples", "", table(Counter(f["failure_mode"] for f in fb), "poor-feedback failure mode"), "",
        table(Counter(f"{f['lang']} / {f['scope']}" for f in fb), "lang / scope"), "",
    ]
    (ROOT / "STATS.md").write_text("\n".join(lines), encoding="utf-8")
    print("  STATS.md")


if __name__ == "__main__":
    main()
